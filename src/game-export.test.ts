import "fake-indexeddb/auto";
import { afterEach, expect, it, vi } from "vitest";
import { clear } from "idb-keyval";
import { exportGame } from "./game-export";
import { exportProject, importProject, loadProject, migrateProjects, saveProject, saveProjectWithImages } from "./project-storage";
import { saveState } from "./save-state";
import { memoryStore } from "./test-helpers";
import type { Project } from "./sandbox";

afterEach(() => { vi.unstubAllGlobals(); });
it("round trips a custom resource, scene and scripts into a self-contained playable export", async () => {
  await clear();
  const store = memoryStore();
  await migrateProjects(store);
  const bytes = Uint8Array.from(atob("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg=="), (c) => c.charCodeAt(0));
  vi.stubGlobal("document", { documentElement: { lang: "en" } });
  const project: Project = { id: "selected", name: '</script><h1>my game</h1>', scripts: { Player: 'class Player extends MonoBehaviour { speed: number = 2; }' }, level: { boxes: [{ tag: "Player", x: 0, y: 0, w: 20, h: 30, color: "red", script: "Player" }], art: { Player: { draw: "stretch", pixel: true } }, camera: { x: 4, y: 5, size: 270 } } };
  await saveProjectWithImages(project, { Player: new Blob([bytes], { type: "image/png" }) }, store);
  const portable = await exportProject(project);
  const restored = await importProject(portable, store);
  expect(restored.id).not.toBe(project.id);
  const loaded = (await loadProject(restored.id, store))!;
  expect(loaded.project.level).toEqual(project.level);
  expect(loaded.project.scripts).toEqual(project.scripts);
  expect(new Uint8Array(await loaded.images.Player.arrayBuffer())).toEqual(bytes);
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue({ ok: true, arrayBuffer: async () => new Uint8Array([1, 2, 3]).buffer }));
  const html = await exportGame(loaded.project, loaded.images);
  expect(html).toContain("&lt;/script&gt;&lt;h1&gt;my game&lt;/h1&gt;");
  const data = JSON.parse(html.match(/id="game-data">(.*?)<\/script>/s)![1]);
  expect(data.project.id).toBeUndefined();
  expect(data.project.scripts.Player).not.toContain(": number");
  expect(data.images.Player).toMatch(/^data:image\/png;base64,/);
  expect(data.font).toMatch(/^data:font\/ttf;base64,/);
  expect(Object.keys(data.sounds)).toHaveLength(10);
  expect(html).not.toMatch(/<script[^>]+src=/);
  expect(html).not.toContain("monaco-editor");
  expect(await loadProject(project.id, store)).toBeDefined();
  await clear();
  const cleanStore = memoryStore();
  await migrateProjects(cleanStore);
  const cleanCopy = await importProject(portable, cleanStore);
  const reopened = (await loadProject(cleanCopy.id, cleanStore))!;
  expect(reopened.project.scripts).toEqual(project.scripts);
  expect(new Uint8Array(await reopened.images.Player.arrayBuffer())).toEqual(bytes);
});
it("fails export instead of silently omitting a missing runtime asset", async () => {
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue({ ok: false, status: 404 }));
  await expect(exportGame({ id: "x", name: "x", scripts: {}, level: { boxes: [] } }, {})).rejects.toThrow("404");
});

it("exports current code and images after storage failure without clearing the warning", async () => {
  const show = vi.fn();
  const state = saveState(show);
  const project: Project = { id: "unsaved", name: "Latest work", scripts: { Player: "class Player extends MonoBehaviour {}" }, level: { boxes: [] } };
  const images = { Player: new Blob([new Uint8Array([1, 2, 3])], { type: "image/png" }) };
  const brokenStore = { getItem: () => null, setItem: () => { throw new Error("disk full"); } };
  expect(await state.track(saveProject(project, brokenStore))).toBe(false);
  const portable = JSON.parse(await exportProject(project, images));
  expect(portable.project.scripts).toEqual(project.scripts);
  expect(portable.images.Player).toBe("data:image/png;base64,AQID");
  vi.stubGlobal("document", { documentElement: { lang: "en" } });
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue({ ok: true, arrayBuffer: async () => new Uint8Array([1]).buffer }));
  const html = await exportGame(project, images);
  const payload = JSON.parse(html.match(/id="game-data">(.*?)<\/script>/s)![1]);
  expect(payload.project.name).toBe(project.name);
  expect(payload.images).toEqual(portable.images);
  expect(state.dirty).toBe(true);
  expect(show).toHaveBeenLastCalledWith("error");
});
